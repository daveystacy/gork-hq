-- EXPIRE offices: the shared, persistent state behind gamey/tradey/arty/betty/story/minty/lobby.expire.org.
-- Already applied to Supabase project expire (szpczmrvthxkdaxqzlqk). Kept here as the record of the schema.
-- Anyone can read (the offices are public pages, same as gork.expire.org). Nobody can write through the public API:
-- Claude chats write through the office_* functions below (not exposed to anon), outside agents through office_api with a token.

create table public.offices (
  id text primary key,
  name text not null,
  domain text not null unique,
  chat_url text,
  chat_online_at timestamptz,
  focus text not null default '',
  updated_at timestamptz not null default now()
);

create table public.office_agents (
  office text not null references public.offices(id) on delete cascade,
  id text not null,
  name text not null,
  role text not null default '',
  color text not null default '#aaaaaa',
  seat int not null default 0,
  state text not null default 'idle' check (state in ('idle','working','meeting','waiting_user')),
  task text not null default '',
  progress int check (progress between 0 and 100),
  since timestamptz not null default now(),
  heard_at timestamptz,
  primary key (office, id)
);

create table public.office_tasks (
  id bigint generated by default as identity primary key,
  office text not null references public.offices(id) on delete cascade,
  title text not null check (char_length(title) <= 200),
  owner text,
  status text not null default 'queued' check (status in ('queued','in-progress','blocked','done')),
  note text not null default '' check (char_length(note) <= 500),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz,
  updated_at timestamptz not null default now()
);
create index office_tasks_office_idx on public.office_tasks (office, updated_at desc);

create table public.office_log (
  id bigint generated by default as identity primary key,
  office text not null references public.offices(id) on delete cascade,
  at timestamptz not null default now(),
  agent text,
  kind text not null default 'note' check (kind in ('note','state','task','deploy','commit','chat')),
  msg text not null check (char_length(msg) <= 500)
);
create index office_log_office_idx on public.office_log (office, at desc);

create table public.office_secret (
  id int primary key default 1 check (id = 1),
  token_sha256 text not null
);

alter table public.offices enable row level security;
alter table public.office_agents enable row level security;
alter table public.office_tasks enable row level security;
alter table public.office_log enable row level security;
alter table public.office_secret enable row level security;

create policy offices_public_read on public.offices for select to anon, authenticated using (true);
create policy office_agents_public_read on public.office_agents for select to anon, authenticated using (true);
create policy office_tasks_public_read on public.office_tasks for select to anon, authenticated using (true);
create policy office_log_public_read on public.office_log for select to anon, authenticated using (true);
-- office_secret has no policies on purpose: the public API can never read it.

-- one row per office for the switcher and the all-offices sheet
create view public.office_summary with (security_invoker = true) as
select o.id, o.name, o.domain, o.chat_url, o.chat_online_at, o.focus,
  (select count(*) from public.office_agents a where a.office = o.id and a.state = 'working') as working,
  (select count(*) from public.office_agents a where a.office = o.id and a.state = 'waiting_user') as waiting,
  (select max(a.heard_at) from public.office_agents a where a.office = o.id) as heard_at,
  (select max(a.heard_at) from public.office_agents a where a.office = o.id and a.state = 'working') as working_heard_at,
  (select count(*) from public.office_tasks t where t.office = o.id and t.status = 'in-progress') as tasks_active,
  (select count(*) from public.office_tasks t where t.office = o.id and t.status = 'queued') as tasks_queued,
  (select count(*) from public.office_tasks t where t.office = o.id and t.status = 'blocked') as tasks_blocked,
  (select count(*) from public.office_tasks t where t.office = o.id and t.status = 'done') as tasks_done,
  (select max(l.at) from public.office_log l where l.office = o.id) as last_activity
from public.offices o;

-- write path -----------------------------------------------------------------------------------------------------------

create function public.office_log_add(p_office text, p_msg text, p_agent text default null, p_kind text default 'note')
returns bigint language plpgsql set search_path = public, pg_temp as $$
declare new_id bigint;
begin
  insert into public.office_log (office, agent, kind, msg) values (p_office, p_agent, p_kind, left(p_msg, 500)) returning id into new_id;
  update public.offices set updated_at = now() where id = p_office;
  return new_id;
end $$;

-- the one call an agent makes as it works: what state it is in, what it is doing, how far along.
-- Every call counts as proof of life (heard_at). A log line is written when the state or task changes, or when p_msg is given.
create function public.office_report(p_office text, p_agent text, p_state text, p_task text default null, p_progress int default null, p_msg text default null)
returns void language plpgsql set search_path = public, pg_temp as $$
declare old public.office_agents; line text;
begin
  select * into old from public.office_agents where office = p_office and id = p_agent for update;
  if not found then raise exception 'no agent % in office %', p_agent, p_office; end if;
  update public.office_agents set
    state = p_state,
    task = case when p_state = 'idle' then coalesce(p_task, '') else coalesce(p_task, task) end,
    progress = case when p_state = 'idle' then null else coalesce(p_progress, case when p_task is distinct from task and p_task is not null then null else progress end) end,
    since = case when state <> p_state or (p_task is not null and p_task is distinct from task) then now() else since end,
    heard_at = now()
  where office = p_office and id = p_agent;
  line := coalesce(p_msg, case
    when old.state <> p_state or (p_task is not null and p_task is distinct from old.task) then
      old.name || ' → ' || replace(p_state, '_', ' ') || case when coalesce(p_task, '') <> '' then ': ' || p_task else '' end
    end);
  if line is not null then perform public.office_log_add(p_office, line, p_agent, 'state'); end if;
  update public.offices set updated_at = now() where id = p_office;
end $$;

create function public.office_task_add(p_office text, p_title text, p_owner text default null, p_status text default 'queued')
returns bigint language plpgsql set search_path = public, pg_temp as $$
declare new_id bigint;
begin
  insert into public.office_tasks (office, title, owner, status, started_at, finished_at)
  values (p_office, p_title, p_owner, p_status,
    case when p_status in ('in-progress','done') then now() end,
    case when p_status = 'done' then now() end)
  returning id into new_id;
  perform public.office_log_add(p_office, 'New task #' || new_id || ': ' || p_title, p_owner, 'task');
  return new_id;
end $$;

create function public.office_task_set(p_id bigint, p_status text, p_note text default null, p_owner text default null)
returns void language plpgsql set search_path = public, pg_temp as $$
declare t public.office_tasks;
begin
  update public.office_tasks set
    status = p_status,
    note = coalesce(p_note, note),
    owner = coalesce(p_owner, owner),
    started_at = case when p_status in ('in-progress','done') then coalesce(started_at, now()) else started_at end,
    finished_at = case when p_status = 'done' then now() else null end,
    updated_at = now()
  where id = p_id returning * into t;
  if not found then raise exception 'no task %', p_id; end if;
  perform public.office_log_add(t.office, 'Task #' || t.id || ' ' || replace(p_status, '-', ' ') || ': ' || t.title || case when coalesce(p_note, '') <> '' then ' (' || p_note || ')' else '' end, t.owner, 'task');
end $$;

-- the headline under the office name
create function public.office_focus(p_office text, p_focus text)
returns void language sql set search_path = public, pg_temp as $$
  update public.offices set focus = left(coalesce(p_focus, ''), 200), updated_at = now() where id = p_office;
$$;

-- a chat checking in: stamps the time and, when known, where its chat lives
create function public.office_chat_checkin(p_office text, p_chat_url text default null, p_msg text default null)
returns void language plpgsql set search_path = public, pg_temp as $$
begin
  update public.offices set chat_online_at = now(), chat_url = coalesce(p_chat_url, chat_url), updated_at = now() where id = p_office;
  if not found then raise exception 'no office %', p_office; end if;
  if p_msg is not null then perform public.office_log_add(p_office, p_msg, null, 'chat'); end if;
end $$;

-- for agents that can't reach the database tools (a script, another AI, a GitHub Action): same calls, behind a token
create function public.office_api(p_token text, p_action text, p_args jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare a jsonb := coalesce(p_args, '{}'::jsonb); out_id bigint;
begin
  if p_token is null or encode(sha256(convert_to(p_token, 'UTF8')), 'hex') is distinct from (select token_sha256 from public.office_secret where id = 1) then
    raise exception 'unauthorized' using errcode = '42501';
  end if;
  case p_action
    when 'report' then perform public.office_report(a->>'office', a->>'agent', a->>'state', a->>'task', (a->>'progress')::int, a->>'msg');
    when 'task_add' then out_id := public.office_task_add(a->>'office', a->>'title', a->>'owner', coalesce(a->>'status', 'queued'));
    when 'task_set' then perform public.office_task_set((a->>'id')::bigint, a->>'status', a->>'note', a->>'owner');
    when 'log' then out_id := public.office_log_add(a->>'office', a->>'msg', a->>'agent', coalesce(a->>'kind', 'note'));
    when 'focus' then perform public.office_focus(a->>'office', a->>'focus');
    else raise exception 'unknown action %', p_action;
  end case;
  return jsonb_build_object('ok', true, 'id', out_id);
end $$;

